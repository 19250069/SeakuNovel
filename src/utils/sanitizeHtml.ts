/**
 * Lightweight HTML sanitizer for chapter content.
 *
 * Allows only the tags and attributes that the Tiptap editor can produce:
 * p, h1, h2, h3, strong, em, u, blockquote, ul, ol, li, hr, br.
 *
 * Strips: script, style, iframe, img, a, and any event handler attributes
 * (on*), javascript: URLs, and data: URLs.
 *
 * This is a defense-in-depth measure. The Tiptap editor only produces safe
 * HTML, but we sanitize on render in case content was inserted via other
 * means (e.g., direct DB edits, seed data, or API calls).
 */

const ALLOWED_TAGS = new Set([
  "p", "h1", "h2", "h3", "h4", "h5", "h6",
  "strong", "b", "em", "i", "u", "s",
  "blockquote", "ul", "ol", "li",
  "hr", "br", "span",
  // "img" intentionally excluded — Tiptap chapter editor does not produce img tags.
  // Allowing img with external src would enable third-party tracking of every reader.
]);

const ALLOWED_ATTRS = new Set(["style", "alt", "title", "width", "height"]);
// "src" excluded: no img tag means src is irrelevant. If img is re-added later,
// src must be validated against an allowlist of trusted domains.

const ALLOWED_STYLE_PROPS = new Set([
  "text-align", "text-indent", "font-weight", "font-style",
  "text-decoration", "color",
]);

export function sanitizeHtml(html: string): string {
  if (!html) return "";

  // Quick check: if no HTML tags at all, wrap in <p> tags for plain text content
  // (handles legacy chapters that were stored as plain text)
  if (!/<[^>]+>/.test(html)) {
    return html
      .split(/\n\n+/)
      .filter((p) => p.trim())
      .map((p) => `<p>${p.replace(/\n/g, "<br>")}</p>`)
      .join("");
  }

  // Use DOMParser for robust parsing (available in browsers)
  if (typeof DOMParser !== "undefined") {
    const parser = new DOMParser();
    const doc = parser.parseFromString(html, "text/html");

    // Remove disallowed elements entirely
    const disallowed = doc.querySelectorAll(
      "script, style, iframe, object, embed, link, meta, a, video, audio, input, form, button"
    );
    disallowed.forEach((el) => el.remove());

    // Walk all elements and clean attributes
    const allElements = doc.querySelectorAll("*");
    allElements.forEach((el) => {
      const tag = el.tagName.toLowerCase();

      // Skip root elements that are always generated by DOMParser
      if (tag === "html" || tag === "head" || tag === "body") return;

      // Remove elements not in allowlist
      if (!ALLOWED_TAGS.has(tag)) {
        // For unknown elements, unwrap them (keep text content)
        const parent = el.parentNode;
        if (parent) {
          while (el.firstChild) {
            parent.insertBefore(el.firstChild, el);
          }
          parent.removeChild(el);
        }
        return;
      }

      // Clean attributes
      const attrs = Array.from(el.attributes);
      attrs.forEach((attr) => {
        const name = attr.name.toLowerCase();
        const value = attr.value;

        // Remove event handlers
        if (name.startsWith("on")) {
          el.removeAttribute(attr.name);
          return;
        }

        // Remove javascript: and data: URLs from any attribute
        if (value && (value.toLowerCase().includes("javascript:") || value.toLowerCase().startsWith("data:"))) {
          el.removeAttribute(attr.name);
          return;
        }

        // Only allow specific attributes
        if (!ALLOWED_ATTRS.has(name)) {
          el.removeAttribute(attr.name);
          return;
        }

        // Sanitize style attribute — only allow safe properties
        if (name === "style") {
          const safeStyles = value
            .split(";")
            .map((s) => s.trim())
            .filter((s) => {
              const prop = s.split(":")[0]?.trim().toLowerCase();
              return prop && ALLOWED_STYLE_PROPS.has(prop);
            })
            .join("; ");
          if (safeStyles) {
            el.setAttribute("style", safeStyles);
          } else {
            el.removeAttribute("style");
          }
        }
      });
    });

    return doc.body.innerHTML;
  }

  // Fallback for non-browser environments (SSR) — basic regex strip
  return html
    .replace(/<script[^>]*>[\s\S]*?<\/script>/gi, "")
    .replace(/<style[^>]*>[\s\S]*?<\/style>/gi, "")
    .replace(/<iframe[^>]*>[\s\S]*?<\/iframe>/gi, "")
    .replace(/\son\w+="[^"]*"/gi, "")
    .replace(/\son\w+='[^']*'/gi, "")
    .replace(/javascript:/gi, "");
}

export default sanitizeHtml;